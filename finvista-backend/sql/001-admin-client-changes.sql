CREATE TABLE IF NOT EXISTS admin_client_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    usuario_nome VARCHAR(120) NOT NULL,
    nome_anterior VARCHAR(150) NOT NULL,
    nome_novo VARCHAR(150) NOT NULL,
    ativo_anterior BOOLEAN NOT NULL,
    ativo_novo BOOLEAN NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL
);