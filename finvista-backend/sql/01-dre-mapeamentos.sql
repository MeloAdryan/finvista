BEGIN;
CREATE TABLE IF NOT EXISTS dre_mapeamentos (
 id UUID PRIMARY KEY,
 cliente_id BIGINT NOT NULL,
 categoria_chave VARCHAR(300) NOT NULL,
 categoria VARCHAR(255) NOT NULL,
 tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('RECEITA','DESPESA')),
 grupo VARCHAR(60) NOT NULL CHECK (grupo IN ('RECEITA_OPERACIONAL','DEDUCOES_RECEITA','CUSTOS','DESPESAS_OPERACIONAIS','RECEITA_FINANCEIRA','DESPESA_FINANCEIRA','FORA_DRE')),
 revisado_em TIMESTAMP WITH TIME ZONE NOT NULL,
 revisado_por BIGINT NOT NULL,
 observacao VARCHAR(1000),
 versao BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uk_dre_cliente_categoria UNIQUE(cliente_id,categoria_chave)
);
COMMIT;
