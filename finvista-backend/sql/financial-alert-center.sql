CREATE TABLE IF NOT EXISTS financial_alert_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
    chave VARCHAR(600) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    gravidade VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    prioridade INTEGER NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    dados TEXT NOT NULL,
    ocorrencias INTEGER NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    alterado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    verificado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    notificado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    resolvido_em TIMESTAMP WITH TIME ZONE,
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_financial_alert_cliente_chave UNIQUE (cliente_id, chave),
    CONSTRAINT ck_financial_alert_periodo CHECK (data_inicio <= data_fim),
    CONSTRAINT ck_financial_alert_ocorrencias CHECK (ocorrencias >= 1)
);

CREATE INDEX IF NOT EXISTS idx_financial_alert_cliente_periodo
    ON financial_alert_records (cliente_id, data_inicio, data_fim);

CREATE TABLE IF NOT EXISTS financial_alert_reads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_id BIGINT NOT NULL REFERENCES financial_alert_records(id) ON DELETE CASCADE,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    lido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_financial_alert_read_usuario UNIQUE (alerta_id, usuario_id)
);

CREATE INDEX IF NOT EXISTS idx_financial_alert_read_usuario
    ON financial_alert_reads (usuario_id, alerta_id);
