CREATE TABLE IF NOT EXISTS classificacoes_custo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    categoria_chave VARCHAR(255) NOT NULL,
    comportamento VARCHAR(30) NOT NULL DEFAULT 'NAO_CLASSIFICADO',
    natureza VARCHAR(30) NOT NULL DEFAULT 'NAO_CLASSIFICADO',
    CONSTRAINT uk_classificacao_cliente_categoria UNIQUE (cliente_id, categoria_chave)
);